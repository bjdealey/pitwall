import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runnerImport } from 'vite';

// Event times render in local time; pin it so every run writes the same previews.
process.env.TZ = 'Europe/London';

type Card = { name: string; group: string; height: number; width?: number; subtitle: string; readme: string; html: string };
type Style = { name: string; fontStretch?: string };
type Tokens = { type: { fonts: unknown[]; groups: { styles: Style[] }[] } };

const path = (p: string) => fileURLToPath(new URL(`../${p}`, import.meta.url));
const OUT = path('dist/design-system/project/');
const FONT = 'archivo-latin-wdth-normal.woff2';

const write = (file: string, text: string) => {
  mkdirSync(dirname(OUT + file), { recursive: true });
  writeFileSync(OUT + file, text);
};

rmSync(path('dist/design-system'), { recursive: true, force: true });

const tokens: Tokens = JSON.parse(readFileSync(path('design/tokens.json'), 'utf8'));
tokens.type.fonts = [{ family: 'Archivo Variable', file: `fonts/${FONT}`, weight: '100 900' }];
write('tokens.json', `${JSON.stringify(tokens, null, 2)}\n`);
mkdirSync(OUT + 'fonts', { recursive: true });
copyFileSync(path(`node_modules/@fontsource-variable/archivo/files/${FONT}`), OUT + `fonts/${FONT}`);

write('README.md', readFileSync(path('design/brand-book.md'), 'utf8'));
write('product.md', readFileSync(path('design/product.md'), 'utf8'));

// The system's generated @font-face has no font-stretch range, so font-stretch would clamp to normal. The width axis is set directly.
const wdth = (css: string) => css.replace(/font-stretch: ([\d.]+)%/g, 'font-variation-settings: "wdth" $1');
const styles = tokens.type.groups.flatMap((g) => g.styles);
write(
  'components/bundle.css',
  [
    '/* Generated by scripts/design-system.ts from src/web/pitwall.css. Do not edit. */',
    ...styles.filter((s) => s.fontStretch).map((s) => wdth(`.${s.name} { font-stretch: ${s.fontStretch}; }`)),
    wdth(readFileSync(path('src/web/pitwall.css'), 'utf8')),
  ].join('\n'),
);

// The app's type classes are pw-<style>; the system's tokens.css names them <style>. Previews carry both.
const typeNames = new Set(styles.map((s) => s.name));
const systemType = (html: string) =>
  html.replace(/class="([^"]*)"/g, (_, list: string) => `class="${list.split(' ').flatMap((c) => (c.startsWith('pw-') && typeNames.has(c.slice(3)) ? [c, c.slice(3)] : [c])).join(' ')}"`);

const preview = (marker: string, title: string, body: string) =>
  `<!-- @dsCard ${marker} -->\n<!doctype html>\n<html lang="en">\n<head><meta charset="utf-8"><title>${title}</title></head>\n<body>\n${body}\n</body>\n</html>\n`;

const { module } = await runnerImport<{ renderCards: () => Card[] }>(path('src/web/design-system.tsx'), { configFile: path('vite.config.ts'), logLevel: 'error' });
for (const card of module.renderCards()) {
  const marker = [`group="${card.group}"`, `height=${card.height}`, card.width ? `width=${card.width}` : '', `subtitle="${card.subtitle}"`].filter(Boolean).join(' ');
  write(`components/${card.name}/preview.html`, preview(marker, card.name, systemType(card.html)));
  write(`components/${card.name}/README.md`, `# ${card.name}\n\n${card.readme}\n`);
}

const PITCH = 24;
const checks = Array.from({ length: 6 * 7 }, (_, i) => [i % 7, Math.floor(i / 7)] as const)
  .filter(([c, r]) => (c + r) % 2 === 0)
  .map(([c, r]) => `<rect class="cut sq" x="${328 + c * PITCH}" y="${24 + r * PITCH}" width="${PITCH}" height="${PITCH}"/>`);

write(
  'components/Cover/preview.html',
  preview(
    'height=288',
    'Pitwall',
    `<style>
  html, body { margin: 0; height: 100%; overflow: hidden; }
  .cover { position: relative; height: 288px; overflow: hidden; background: var(--bg); }
  .art { position: absolute; top: 0; left: 480px; width: 480px; height: 288px; overflow: hidden; }
  .art svg { display: block; }
  .ink { fill: var(--fg); }
  .cut { fill: var(--surface); }
  .yellow { fill: var(--flag-yellow); }
  .red { fill: var(--flag-red); }
  .green { fill: var(--flag-green); }
  .best { fill: var(--best); }
  .blk { rx: var(--radius-sm); }
  .words { position: absolute; left: var(--space-6); bottom: var(--space-6); max-width: 440px; }
  .name { margin: 0; font-family: var(--font-sans); font-size: 112px; line-height: .92; font-weight: 800; font-variation-settings: "wdth" 75; letter-spacing: -.01em; color: var(--fg); }
  .tagline { margin: var(--space-2) 0 0; font-family: var(--font-sans); font-size: 14px; line-height: 20px; color: var(--muted); }
</style>
<div class="cover">
<div class="art" aria-hidden="true">
<svg viewBox="0 0 480 288" width="480" height="288">
<!--
  blocks      fg slab 264x240 bleeding off the right (the timing screen); flag-yellow 192x96 and flag-red 120x128 (the flags people know a pit wall by); flag-green and best 56x56 kept small (the calm flag and sector purple)
  arrangement a column of flags on the left, the timing-screen slab beside them bleeding right; tops on space-6, gutters space-4
  pattern     a chequered flag cut into the slab's top-right in surface, from the track band's chequered state: ${checks.length} squares at a space-6 pitch
  scales      sides in space-2 multiples; gutters space-4; checker pitch space-6; every corner radius-sm, because screens are hardware
-->
<rect class="yellow blk" x="24" y="24" width="192" height="96"/>
<rect class="red blk" x="24" y="136" width="120" height="128"/>
<rect class="green blk" x="160" y="136" width="56" height="56"/>
<rect class="best blk" x="160" y="208" width="56" height="56"/>
<rect class="ink blk" x="232" y="24" width="264" height="240"/>
${checks.join('\n')}
</svg>
</div>
<div class="words">
<h1 class="name">Pitwall</h1>
<p class="tagline">Watch the bot. Stop it fast.</p>
</div>
</div>`,
  ),
);

console.log(`Design system written to ${OUT}`);
